test_that("mlogit, ologit and poisson match R's estimators", {
  d <- mtcars
  ml <- s.mlogit(d, gear, mpg, nolog = TRUE)
  ref <- nnet::multinom(factor(gear, levels = c(3, 4, 5)) ~ mpg, d, trace = FALSE, reltol = 1e-14)
  expect_equal(ml$estimate[ml$equation == "4"], unname(coef(ref)["4", c("mpg", "(Intercept)")]), tolerance = 1e-5)
  expect_equal(s.ereturn(ml)$ll, as.numeric(logLik(ref)), tolerance = 1e-8)

  ol <- s.ologit(d, gear, mpg, wt, nolog = TRUE)
  pr <- MASS::polr(factor(gear) ~ mpg + wt, d, Hess = TRUE)
  # polr() (BFGS) converges less tightly than Newton-Raphson
  expect_equal(ol$estimate[1:2], unname(coef(pr)), tolerance = 2e-3)
  expect_equal(ol$estimate[ol$equation %in% "/"], unname(pr$zeta), tolerance = 2e-3)
  expect_equal(s.ereturn(ol)$ll, as.numeric(logLik(pr)), tolerance = 1e-6)

  po <- s.poisson(warpbreaks, breaks, wool, tension, nolog = TRUE)
  g <- glm(breaks ~ wool + tension, poisson, warpbreaks)
  expect_equal(po$estimate[po$note == ""], unname(coef(g)[c(2, 3, 4, 1)]), tolerance = 1e-7)
  expect_equal(s.ereturn(po)$ll, as.numeric(logLik(g)), tolerance = 1e-9)

  # exposure enters as log offset
  pe <- s.poisson(d, carb, wt, exposure = disp, nolog = TRUE)
  ge <- glm(carb ~ wt + offset(log(disp)), poisson, d)
  expect_equal(pe$estimate[1], unname(coef(ge)[2]), tolerance = 1e-7)
  expect_equal(pe$note[pe$variable == "ln(disp)"], "exposure")
})

test_that("factor-variable notation and base categories", {
  r <- s.regress(mtcars, mpg, "c.wt##i.am", "ib6.cyl")
  expect_true("am#wt" %in% r$variable)
  expect_equal(r$note[r$variable == "cyl" & r$level == "6"], "base")
  expect_error(s.regress(mtcars, mpg, "c.wt##i.nope"), "not found")
  expect_error(s.regress(mtcars, mpg, wt, base = c(wt = 1)), "categorical")
  # the same model through `interact`
  r2 <- s.regress(mtcars, mpg, cyl, categorical = cyl, base = c(cyl = 6), interact = "c.wt##i.am")
  expect_equal(sort(r2$estimate), sort(r$estimate))
})

test_that("margins: values and tidy result", {
  m <- s.logit(mtcars, am, wt, hp, nolog = TRUE)
  a <- s.margins(m, dydx = "*")
  g <- glm(am ~ wt + hp, binomial, mtcars)
  p <- fitted(g)
  expect_equal(a$estimate[1], mean(p * (1 - p)) * unname(coef(g)["wt"]), tolerance = 1e-5)
  b <- s.margins(m, at = list(wt = c(2, 3)))
  expect_equal(b$wt, c(2, 3))
  expect_s3_class(b, "st_margins")
  r <- s.regress(mtcars, mpg, wt, "i.cyl")
  mc <- s.margins(r, cyl)
  expect_equal(nrow(mc), 3)
  expect_true(is.factor(mc$cyl))
  expect_error(s.margins(r, wt), "not a factor variable")
  expect_error(s.margins(dplyr::group_by(mtcars, am) |> s.regress(mpg, wt)), "single model")
  skip_if_not_installed("ggplot2")
  expect_s3_class(s.marginsplot(b), "ggplot")
  expect_s3_class(s.marginsplot(mc), "ggplot")
  expect_s3_class(s.marginsplot(a), "ggplot")
})

test_that("predict, estat and diagnostic plots", {
  r <- s.regress(mtcars, mpg, wt, hp)
  d <- s.predict(mtcars, r, "yhat")
  expect_equal(d$yhat, unname(fitted(lm(mpg ~ wt + hp, mtcars))))
  d <- s.predict(d, r, "rs", type = "rstandard")
  expect_equal(d$rs, unname(rstandard(lm(mpg ~ wt + hp, mtcars))))
  d <- s.predict(d, r, "cd", type = "cooksd")
  expect_equal(d$cd, unname(cooks.distance(lm(mpg ~ wt + hp, mtcars))))
  expect_error(s.predict(mtcars[1:5, ], r, "x", type = "cooksd"), "estimated with")
  ml <- s.mlogit(mtcars, gear, mpg, nolog = TRUE)
  d2 <- s.predict(mtcars, ml, "p")
  expect_equal(unname(rowSums(d2[c("p_3", "p_4", "p_5")])), rep(1, 32))
  h <- s.estat(r, "hettest")
  expect_equal(names(h), c("chi2", "df", "p"))
  expect_error(s.estat(s.logit(mtcars, am, wt, nolog = TRUE), "vif"), "not available")
  t1 <- s.test(r, wt, hp)
  expect_equal(t1$df, 2)
  skip_if_not_installed("ggplot2")
  expect_s3_class(s.rvfplot(r), "ggplot")
  expect_s3_class(s.rvpplot(r, wt), "ggplot")
  expect_s3_class(s.lvr2plot(r), "ggplot")
  expect_s3_class(s.qnorm(d, rs), "ggplot")
  expect_s3_class(s.kdensity(d, rs, normal = TRUE), "ggplot")
})

test_that("new models work with etable and export", {
  ml <- s.mlogit(mtcars, gear, mpg, nolog = TRUE)
  ol <- s.ologit(mtcars, gear, mpg, nolog = TRUE)
  po <- s.poisson(mtcars, carb, wt, nolog = TRUE)
  e <- s.etable(ml, ol, po, mstat = c("N", "r2_p", "ll"))
  out <- capture.output(print(e))
  expect_true(any(grepl("cut1", out, fixed = TRUE)))
  expect_true(any(grepl("^4", out)))
  f <- tempfile(fileext = ".html")
  expect_message(s.export(list(ml, ol, po, s.margins(po, dydx = wt), s.estat(po, "gof")), f))
  html <- paste(readLines(f), collapse = "\n")
  expect_match(html, "mlogit gear mpg", fixed = TRUE)
  expect_match(html, "Delta-method", fixed = TRUE)
})
